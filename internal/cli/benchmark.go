// The benchmarks exist to answer "where does the time go", and they are the instrument
// stage 9 uses. Two of them, measuring different things:
//
//   - crud runs the real commands against a real repository, so it measures everything
//     including the filesystem, the cache and the pack writer.
//   - cpu measures the primitives in isolation, in memory, so a change to one of them can
//     be attributed.
//
// # Comparability is the whole point
//
// A benchmark number that cannot be compared with borg's tells us nothing about the port.
// So the data volumes, the buffer sizes and the output columns are borg's, and the
// compression input is generated by borg's own word-soup PRNG so that both tools compress
// exactly the same bytes. Where borge cannot match - see the chunker setup cost below -
// the difference is reported rather than hidden.

// benchmarkCommands is the dispatch table for "borge benchmark <name>".
//
// A function rather than a package variable: "benchmark crud" runs the ordinary commands
// through Run, so a table built at initialisation would be a cycle through the top-level
// dispatch table back to itself, which Go refuses to order.
func benchmarkCommands() []command {
	return []command{
		{"crud", "measure create, extract, update and delete against a repository", cmdBenchmarkCRUD},
		{"cpu", "measure the CPU-bound primitives", cmdBenchmarkCPU},
	}
}

func cmdBenchmark(e *Env, args []string) int {
	// --log-json may be given to the group as well as to the subcommand; borg
	// accepts it in both places. See takeParentLogJSON.
	args = e.takeParentLogJSON("benchmark", args)
	if len(args) == 0 || groupHelpRequested(args[0]) {
		printBenchmarkUsage(e.Stdout)
		return ExitOK
	}
	name := args[0]
	for _, c := range benchmarkCommands() {
		if c.name == name {
			return c.run(e, args[1:])
		}
	}
	e.errorf("unknown benchmark command %q", name)
	printBenchmarkUsage(e.Stderr)
	return ExitError
}

func printBenchmarkUsage(w io.Writer) {
	var b bytes.Buffer
	for _, c := range benchmarkCommands() {
		fmt.Fprintf(&b, "  %-6s %s\n", c.name, c.summary)
	}
	fmt.Fprintf(w, "usage: borge benchmark <command> [options]\n\ncommands:\n%s%s",
		b.String(), groupUsageOptions)
}

// benchTestMode reports whether the tiny-data mode is on.
//
// It exists so the tests can run these commands at all: the real volumes are a gigabyte
// per row, which is right for a measurement and absurd for a test suite.
func benchTestMode(e *Env, name string) bool {
	if _, ok := e.lookup("_BORGE_BENCHMARK_" + name + "_TEST"); ok {
		return true
	}
	_, ok := e.lookup("_BORG_BENCHMARK_" + name + "_TEST")
	return ok
}

// ---------------------------------------------------------------- crud

// crudSample is one row of the crud benchmark: a number of files of a given size, either
// all-zero or random.
type crudSample struct {
	name   string
	count  int
	size   int
	random bool
}

// crudSamples is borg's set, and the sizes are load-bearing rather than arbitrary.
//
// All-zero files deduplicate completely, so the Z rows measure the reader, the chunker and
// the hash with the store doing almost nothing. Random files deduplicate not at all, so the
// R rows measure the whole pipeline including compression and the pack writer. Running both
// at three scales separates per-byte cost from per-file cost, which is the distinction that
// matters for a directory holding a hundred thousand small files.
var crudSamples = []crudSample{
	{"Z-BIG", 10, 100000000, false},
	{"R-BIG", 10, 100000000, true},
	{"Z-MEDIUM", 1000, 1000000, false},
	{"R-MEDIUM", 1000, 1000000, true},
	{"Z-SMALL", 10000, 10000, false},
	{"R-SMALL", 10000, 10000, true},
}

var crudTestSamples = []crudSample{
	{"Z-TEST", 1, 1, false},
	{"R-TEST", 1, 1, true},
}

// crudTiming is what one sample measured.
type crudTiming struct {
	create, update, extract, delete time.Duration
}

func cmdBenchmarkCRUD(e *Env, args []string) int {
	fs := newFlagSet(e, "benchmark crud")
	var common commonFlags
	common.register(fs)
	jsonLines := fs.Bool("json-lines", false, "print one JSON object per measurement")
	if err := fs.Parse(args); err != nil {
		return ExitError
	}
	if fs.NArg() != 1 {
		e.errorf("benchmark crud needs a path to create its input data under")
		return ExitError
	}
	dataRoot := fs.Arg(0)

	repo, err := e.resolveRepo(common.repo)
	if err != nil {
		return e.fail(err)
	}
	// The repository has to exist already: creating one here would hide the key
	// management, and a benchmark that silently makes a repository in the wrong place is
	// a bad surprise.
	// Only a local repository can be checked this cheaply. A remote one is left to the
	// create below, which fails with the backend's own message rather than a guess made
	// from here.
	if repo.IsLocal() {
		if _, err := os.Stat(filepath.Join(repo.Path, "config", "readme")); err != nil {
			e.errorf("%s is not a repository; create one first (the benchmark writes "+
				"archives named borge-benchmark-crud* into it)", repo)
			return ExitError
		}
	}

	samples := crudSamples
	if benchTestMode(e, "CRUD") {
		samples = crudTestSamples
	}

	for _, s := range samples {
		timing, err := runCRUDSample(e, repo, dataRoot, s)
		if err != nil {
			return e.fail(err)
		}
		total := int64(s.count) * int64(s.size)
		if *jsonLines {
			if err := printCRUDJSON(e, s, timing, total); err != nil {
				return e.fail(err)
			}
			continue
		}
		printCRUDText(e, s, timing, total)
	}
	return ExitOK
}

// runCRUDSample writes the input files, then measures the four operations over them.
func runCRUDSample(e *Env, repo *location.Location, dataRoot string, s crudSample) (crudTiming, error) {
	dir, err := os.MkdirTemp(dataRoot, "borge-test-data-")
	if err != nil {
		return crudTiming{}, err
	}
	defer os.RemoveAll(dir)

	// The zero buffer is made once and reused; the random one is fresh per file, because
	// a repeated random buffer would deduplicate and turn the R rows into Z rows.
	zeros := make([]byte, s.size)
	for i := 0; i < s.count; i++ {
		data := zeros
		if s.random {
			data = make([]byte, s.size)
			if _, err := rand.Read(data); err != nil {
				return crudTiming{}, err
			}
		}
		name := filepath.Join(dir, fmt.Sprintf("file_%d", i))
		if err := os.WriteFile(name, data, 0o600); err != nil {
			return crudTiming{}, err
		}
	}
	return measureCRUD(e, repo, dir)
}

// measureCRUD runs the commands, in borg's order and with borg's arguments.
func measureCRUD(e *Env, repo *location.Location, path string) (crudTiming, error) {
	var t crudTiming

	// Every sub-command runs through the ordinary dispatch, so what is measured is what a
	// user gets rather than a special path that might be faster.
	run := func(args ...string) error {
		// The openable form, not the canonical one: these sub-commands have to open the
		// repository, and canonicalisation removes any credentials it carries.
		return runQuiet(e, append([]string{args[0], "-r", repo.Openable()}, args[1:]...)...)
	}
	timed := func(fn func() error) (time.Duration, error) {
		start := time.Now()
		err := fn()
		return time.Since(start), err
	}
	var err error

	// C: a first archive, with the files cache off so the chunker actually runs.
	if t.create, err = timed(func() error {
		return run("create", "-C", "none", "--files-cache", "disabled", "borge-benchmark-crud1", path)
	}); err != nil {
		return t, err
	}

	// Build the files cache, so the U measurement below is a cache hit rather than a
	// second cold run. Not timed.
	if err := run("create", "-C", "none", "borge-benchmark-crud2", path); err != nil {
		return t, err
	}
	if err := run("delete", "borge-benchmark-crud2"); err != nil {
		return t, err
	}

	// U: an unchanged re-backup. The throughput figure is virtual - nothing is read - and
	// it is the files cache that is being measured.
	if t.update, err = timed(func() error {
		return run("create", "-C", "none", "borge-benchmark-crud3", path)
	}); err != nil {
		return t, err
	}
	if err := run("delete", "borge-benchmark-crud3"); err != nil {
		return t, err
	}

	// R: a dry-run extract, which does all the reading and decrypting but writes nothing,
	// so the number is not dominated by the output filesystem.
	if t.extract, err = timed(func() error {
		return run("extract", "--dry-run", "borge-benchmark-crud1")
	}); err != nil {
		return t, err
	}

	// D: deleting the last archive holding the data.
	if t.delete, err = timed(func() error {
		return run("delete", "borge-benchmark-crud1")
	}); err != nil {
		return t, err
	}
	return t, nil
}

// runQuiet dispatches a command with its output discarded, keeping stderr only to report
// what went wrong if it fails.
func runQuiet(e *Env, args ...string) error {
	var stderr bytes.Buffer
	sub := &Env{Stdout: io.Discard, Stderr: &stderr, Stdin: e.Stdin, Getenv: e.Getenv}
	if code := Run(sub, args); code != ExitOK {
		return fmt.Errorf("borge %s exited %d: %s", args[0], code, stderr.String())
	}
	return nil
}

// crudJSON is one --json-lines record. The fields are in borg's order, which is
// alphabetical because borg dumps this dict with sort_keys.
type crudJSON struct {
	Command      string  `json:"command"`
	ID           string  `json:"id"`
	IO           int64   `json:"io"`
	Sample       string  `json:"sample"`
	SampleCount  int     `json:"sample_count"`
	SampleRandom bool    `json:"sample_random"`
	SampleSize   int     `json:"sample_size"`
	Time         float64 `json:"time"`
}

// crudOps pairs each measurement with the letter and command name borg reports it under.
var crudOps = []struct {
	letter  string
	command string
	pick    func(crudTiming) time.Duration
}{
	{"C", "create1", func(t crudTiming) time.Duration { return t.create }},
	{"R", "extract", func(t crudTiming) time.Duration { return t.extract }},
	{"U", "create2", func(t crudTiming) time.Duration { return t.update }},
	{"D", "delete", func(t crudTiming) time.Duration { return t.delete }},
}

func printCRUDJSON(e *Env, s crudSample, t crudTiming, total int64) error {
	enc := json.NewEncoder(e.Stdout)
	for _, op := range crudOps {
		dt := op.pick(t).Seconds()
		rec := crudJSON{
			Command: op.command, ID: op.letter + "-" + s.name, Sample: s.name,
			SampleCount: s.count, SampleRandom: s.random, SampleSize: s.size, Time: dt,
		}
		if dt > 0 {
			rec.IO = int64(float64(total) / dt)
		}
		if err := enc.Encode(rec); err != nil {
			return err
		}
	}
	return nil
}

func printCRUDText(e *Env, s crudSample, t crudTiming, total int64) {
	totalMB := float64(total) / 1e6
	size := e.fmtBytes(int64(s.size))
	content := "all-zero"
	if s.random {
		content = "random"
	}
	for _, op := range crudOps {
		dt := op.pick(t).Seconds()
		rate := 0.0
		if dt > 0 {
			rate = totalMB / dt
		}
		fmt.Fprintf(e.Stdout, "%s-%-10s %9.2f MB/s (%d * %s %s files: %.2fs)\n",
			op.letter, s.name, rate, s.count, size, content, dt)
	}
}

// ---------------------------------------------------------------- cpu

// Buffer sizes and totals, all powers of two so a section's total is exactly 1 GiB rather
// than an awkward fraction of it.
const (
	kiB = 1024
	miB = 1024 * kiB
	giB = 1024 * miB
)

// benchSize is a buffer size with the label borg prints for it.
type benchSize struct {
	label string
	bytes int
}

var (
	sizeSmall = benchSize{"128kiB", 128 * kiB}
	sizeChunk = benchSize{"2MiB", 2 * miB}
	sizePack  = benchSize{"64MiB", 64 * miB}
)

// benchWidth is the width of the spec column, wide enough for the longest row of any
// section so the sections line up with each other. borg's value.
const benchWidth = 26

// cpuBench holds the sizes and repetition counts one run works at.
type cpuBench struct {
	e    *Env
	json bool

	// result collects the rows when --json is on.
	result map[string][]any

	chunkDataSize int
	number        int
	hashSizes     []benchSize
	compSizes     []benchSize
	oneSize       []benchSize
	hashTotal     int
	compTotal     int

	buffers     map[int][]byte
	compressibl map[int][]byte
}

func cmdBenchmarkCPU(e *Env, args []string) int {
	fs := newFlagSet(e, "benchmark cpu")
	asJSON := fs.Bool("json", false, "print JSON instead of text")
	chunking := fs.Bool("chunking", false, "benchmark the chunkers")
	hashing := fs.Bool("hashing", false, "benchmark the hashes and MACs")
	encrypting := fs.Bool("encrypting", false, "benchmark the encryption modes")
	compressing := fs.Bool("compressing", false, "benchmark the compressors")
	msgpacking := fs.Bool("msgpacking", false, "benchmark item packing")
	if err := fs.Parse(args); err != nil {
		return ExitError
	}

	selected := map[string]bool{}
	for name, on := range map[string]*bool{
		"chunking": chunking, "hashing": hashing, "encrypting": encrypting,
		"compressing": compressing, "msgpacking": msgpacking,
	} {
		if *on {
			selected[name] = true
		}
	}
	if len(selected) == 0 {
		for _, name := range []string{"chunking", "hashing", "encrypting", "compressing", "msgpacking"} {
			selected[name] = true
		}
	}

	b := &cpuBench{
		e: e, json: *asJSON, result: map[string][]any{},
		buffers: map[int][]byte{}, compressibl: map[int][]byte{},
	}
	if benchTestMode(e, "CPU") {
		b.chunkDataSize = 128 * kiB
		b.number = 1
		b.hashSizes = []benchSize{sizeSmall}
		b.compSizes = []benchSize{sizeSmall}
		b.oneSize = []benchSize{sizeSmall}
		b.hashTotal = sizeSmall.bytes
		b.compTotal = sizeSmall.bytes
	} else {
		b.chunkDataSize = 8 * miB
		b.number = giB / (8 * miB)
		// blake3 is the only hash whose behaviour depends on the buffer size, so it is
		// the one measured at more than one: a borg pack, then a borg chunk.
		b.hashSizes = []benchSize{sizePack, sizeChunk}
		b.compSizes = []benchSize{sizeSmall, sizeChunk}
		b.oneSize = []benchSize{sizeChunk}
		b.hashTotal = giB
		// Compressible data means the codecs actually work, so the slow ones need fewer
		// bytes to stay bearable.
		b.compTotal = 10 * miB
	}

	if selected["chunking"] {
		if err := b.chunkers(); err != nil {
			return e.fail(err)
		}
	}
	if selected["hashing"] {
		if err := b.hashes(); err != nil {
			return e.fail(err)
		}
	}
	if selected["encrypting"] {
		if err := b.encryption(); err != nil {
			return e.fail(err)
		}
	}
	if selected["compressing"] {
		if err := b.compression(); err != nil {
			return e.fail(err)
		}
	}
	if selected["msgpacking"] {
		if err := b.msgpacking(); err != nil {
			return e.fail(err)
		}
	}

	if b.json {
		enc := json.NewEncoder(e.Stdout)
		enc.SetIndent("", "  ")
		if err := enc.Encode(b.result); err != nil {
			return e.fail(err)
		}
	}
	return ExitOK
}

// buffer returns random data of the given size, made once and reused.
func (b *cpuBench) buffer(n int) []byte {
	if buf, ok := b.buffers[n]; ok {
		return buf
	}
	buf := make([]byte, n)
	if _, err := rand.Read(buf); err != nil {
		panic(err) // crypto/rand failing means the machine is broken
	}
	b.buffers[n] = buf
	return buf
}

func (b *cpuBench) section(name, title string) {
	if b.json {
		b.result[name] = []any{}
		return
	}
	line := title + " "
	for len(line) < 64 {
		line += "="
	}
	fmt.Fprintln(b.e.Stdout, line)
}

// report prints or records one row.
//
// size is the total number of bytes the row processed, so the throughput column is
// comparable between rows even when they used different buffer sizes.
func (b *cpuBench) report(section, spec string, size int64, dt time.Duration, extra map[string]any, note string) {
	if b.json {
		row := map[string]any{"size": size, "time": dt.Seconds()}
		for k, v := range extra {
			row[k] = v
		}
		if note != "" {
			row["note"] = note
		}
		b.result[section] = append(b.result[section], row)
		return
	}
	line := fmt.Sprintf("%-*s %-11s %.3fs  %8.1f MB/s",
		benchWidth, spec, formatBytesIn(size, "iec"), dt.Seconds(),
		float64(size)/dt.Seconds()/1e6)
	if note != "" {
		line += "  " + note
	}
	fmt.Fprintln(b.e.Stdout, line)
}

// ---- chunkers

// chunkerSpecs are the chunkers borge implements. borg's benchmark also lists the
// experimental AES-based ones; borge refuses those (see internal/chunker/chunker.go), so
// benchmarking them would measure an error path.
var chunkerSpecs = []string{
	"fixed,1048576",
	"fastcdc,19,23,21,2",
	"buzhash64,19,23,21,4095,2",
	"buzhash,19,23,21,4095",
}

// chunkers measures chunking throughput, and separately the cost of building a chunker.
//
// # Why the setup cost is a column of its own
//
// borg builds one chunker per *archive* and reuses it for every file
// (`FilesystemObjectProcessors.__init__`), so its benchmark can put construction in the
// timeit setup and measure only the chunking loop. borge builds one per *file*
// (`archive.Builder.ChunkFile`), so construction is a real per-file cost here and leaving
// it out of the measurement would flatter the port.
//
// It is not small. The gear and buzhash tables take milliseconds to build, which is
// nothing beside a large file and everything beside a small one - so for a directory of a
// hundred thousand small files it is a dominant cost that no throughput number would
// reveal. Reporting it separately is what makes it visible.
func (b *cpuBench) chunkers() error {
	b.section("chunkers", "Chunkers")
	key := b.buffer(32)
	data := b.buffer(b.chunkDataSize)
	size := int64(b.chunkDataSize) * int64(b.number)

	for _, spec := range chunkerSpecs {
		params, err := chunker.ParseParams(spec)
		if err != nil {
			return err
		}

		// Construction alone, so it can be subtracted from - and reported beside - the
		// combined figure below.
		start := time.Now()
		for i := 0; i < b.number; i++ {
			if _, err := chunker.New(params, key, 0, bytes.NewReader(nil)); err != nil {
				return err
			}
		}
		setup := time.Since(start)

		start = time.Now()
		for i := 0; i < b.number; i++ {
			ch, err := chunker.New(params, key, 0, bytes.NewReader(data))
			if err != nil {
				return err
			}
			for {
				if _, err := ch.Next(); err == io.EOF {
					break
				} else if err != nil {
					return err
				}
			}
		}
		total := time.Since(start)

		algo, params2 := splitSpec(spec)
		perFile := setup / time.Duration(b.number)
		note := fmt.Sprintf("(setup %s/file, %.0f%%)", perFile.Round(time.Microsecond),
			100*float64(setup)/float64(total))
		b.report("chunkers", spec, size, total, map[string]any{
			"algo": algo, "algo_params": params2,
			"setup_time": setup.Seconds(), "setup_per_call": perFile.Seconds(),
		}, note)
	}
	return nil
}

func splitSpec(spec string) (algo, params string) {
	for i := 0; i < len(spec); i++ {
		if spec[i] == ',' {
			return spec[:i], spec[i+1:]
		}
	}
	return spec, ""
}

// ---- hashes

func (b *cpuBench) hashes() error {
	b.section("hashes", "Cryptographic hashes / MACs")
	key := b.buffer(32)

	// blake3 is measured at two buffer sizes because borg's is multi-threaded above a
	// threshold and behaves quite differently either side of it. borge's blake3 is
	// single-threaded (lukechampine.com/blake3), so the two rows should be close together
	// here and far apart in borg's output - which is exactly the comparison worth having.
	tests := []struct {
		spec  string
		sizes []benchSize
		fn    func(data []byte) error
	}{
		{"blake3", b.hashSizes, func(d []byte) error { _, err := crypto.Blake3Keyed(key, d); return err }},
		{"hmac-sha256", b.oneSize, func(d []byte) error { crypto.HMACSHA256(key, d); return nil }},
		{"blake2b-256", b.oneSize, func(d []byte) error { crypto.Blake2b256(key, d); return nil }},
	}

	for _, t := range tests {
		for _, s := range t.sizes {
			data := b.buffer(s.bytes)
			n := max(1, b.hashTotal/s.bytes)
			start := time.Now()
			for i := 0; i < n; i++ {
				if err := t.fn(data); err != nil {
					return err
				}
			}
			dt := time.Since(start)
			b.report("hashes", fmt.Sprintf("%s (%s)", t.spec, s.label),
				int64(s.bytes)*int64(n), dt,
				map[string]any{"algo": t.spec, "buffer_size": s.bytes}, "")
		}
	}
	return nil
}

// ---- encryption

func (b *cpuBench) encryption() error {
	b.section("encryption", "Encryption")
	key := b.buffer(32)
	iv := b.buffer(12)
	data := b.buffer(b.chunkDataSize)
	size := int64(b.chunkDataSize) * int64(b.number)
	header := []byte("X")

	// The two AEAD suites borge implements. borg also benchmarks its borg 1.x
	// encrypt-then-MAC modes; borge does not implement those at all - see
	// docs/PORTING_PLAN.md 0.1 - so there is nothing to measure.
	for _, t := range []struct {
		spec  string
		suite crypto.Suite
	}{
		{"aes-256-ocb", crypto.SuiteAESOCB},
		{"chacha20-poly1305", crypto.SuiteChaCha20Poly1305},
	} {
		aead, err := crypto.NewAEAD(t.suite, key, 1, 1)
		if err != nil {
			return err
		}
		start := time.Now()
		for i := 0; i < b.number; i++ {
			if _, err := aead.Encrypt(iv, data, header, nil); err != nil {
				return err
			}
		}
		dt := time.Since(start)
		b.report("encryption", t.spec, size, dt, map[string]any{"algo": t.spec}, "")
	}
	return nil
}

// ---- compression

// compressionSpecs are measured in this order so the codecs can be compared at a glance
// within one buffer size.
var compressionSpecs = []string{
	"lz4",
	"zstd,1", "zstd,3", "zstd,5", "zstd,10", "zstd,16", "zstd,22",
	"zlib,1", "zlib,6", "zlib,9",
	"lzma,0", "lzma,6", "lzma,9",
}

func (b *cpuBench) compression() error {
	b.section("compression", "Compression")
	// Chunk-sized first, since that is what borge actually compresses.
	for i := len(b.compSizes) - 1; i >= 0; i-- {
		s := b.compSizes[i]
		data := b.compressibleBuffer(s.bytes)
		n := max(3, b.compTotal/s.bytes) // a few repetitions even for the fast codecs
		for _, spec := range compressionSpecs {
			compressor, err := compress.FromSpec(spec)
			if err != nil {
				return err
			}
			var out []byte
			start := time.Now()
			for j := 0; j < n; j++ {
				var meta compress.Meta
				var err error
				if out, err = compressor.Compress(&meta, data); err != nil {
					return err
				}
			}
			dt := time.Since(start)
			// The ratio is borge's addition, and it is not decoration. borge's zstd is
			// klauspost/compress, whose encoder has four levels rather than libzstd's
			// twenty-two, so several of borge's nominal levels compress identically - and a
			// benchmark reporting only speed would show that as borge being faster than
			// borg at zstd,22 rather than as borge doing less work. The level is metadata
			// and not part of the format, so this costs no interoperability; it costs
			// compression the user asked for, which is worth being able to see.
			ratio := 0.0
			if len(out) > 0 {
				ratio = float64(len(data)) / float64(len(out))
			}
			algo, params := splitSpec(spec)
			b.report("compression", fmt.Sprintf("%s (%s)", spec, s.label),
				int64(s.bytes)*int64(n), dt,
				map[string]any{"algo": algo, "algo_params": params,
					"buffer_size": s.bytes, "ratio": ratio},
				fmt.Sprintf("(%.1fx)", ratio))
		}
	}
	return nil
}

// compressionWords is borg's word list, kept byte for byte: the generated data has to be
// identical in both tools or the compression rows are not comparable.
var compressionWords = bytes.Fields([]byte(
	"backup archive chunk repository compress encrypt index cache manifest " +
		"the and of a to in is it for with data borg file path size key id hash " +
		"item repo object segment directory user group mtime mode owner content"))

// compressibleBuffer builds deterministic, text-like, compressible data.
//
// Random bytes are the worst possible input for a compression benchmark: nothing
// compresses, every codec takes its incompressible fast path, the levels barely differ,
// and zstd's multi-threading looks like a large loss when on real data it is a win.
//
// The xorshift is written out rather than taken from math/rand so that the bytes do not
// depend on either language's PRNG - borg spells it out for the same reason, and the two
// implementations produce byte-identical data.
func (b *cpuBench) compressibleBuffer(n int) []byte {
	if buf, ok := b.compressibl[n]; ok {
		return buf
	}
	out := make([]byte, 0, n+16)
	state := uint64(0x2545F4914F6CDD1D)
	for len(out) < n {
		state ^= state << 13
		state ^= state >> 7
		state ^= state << 17
		out = append(out, compressionWords[state%uint64(len(compressionWords))]...)
		if state&0xF == 0 {
			out = append(out, '\n')
		} else {
			out = append(out, ' ')
		}
	}
	buf := out[:n]
	b.compressibl[n] = buf
	return buf
}

// ---- msgpack

func (b *cpuBench) msgpacking() error {
	b.section("msgpack", "msgpack")

	mode, mtime := int64(660), int64(1234567)
	it := &item.Item{Path: "foo/bar/baz", Mode: &mode, MTime: &mtime}
	m, err := it.Encode()
	if err != nil {
		return err
	}
	items := make([]any, 1000)
	for i := range items {
		items[i] = m
	}

	count := 1000 * b.number
	start := time.Now()
	for i := 0; i < b.number; i++ {
		if _, err := msgpackx.Marshal(items); err != nil {
			return err
		}
	}
	dt := time.Since(start)

	if b.json {
		b.result["msgpack"] = append(b.result["msgpack"], map[string]any{
			"algo": "msgpack", "count": count, "time": dt.Seconds(),
		})
		return nil
	}
	// This row packs items rather than bytes, so it gets a rate in its own unit.
	fmt.Fprintf(b.e.Stdout, "%-*s %-11s %.3fs  %8.1f kItems/s\n",
		benchWidth, "msgpack", fmt.Sprintf("%dk Items", count/1000), dt.Seconds(),
		float64(count)/dt.Seconds()/1000)
	return nil
}
