// borgeEnvWith is borgeEnv with extra environment variables, for the benchmarks' test-mode
// switch. The real data volumes are a gigabyte per row, which is right for a measurement
// and impossible in a test suite.
func (r *borgRepo) borgeEnvWith(stdout, stderr *bytes.Buffer, extra map[string]string) *Env {
	e := r.borgeEnv(stdout, stderr)
	base := e.Getenv
	e.Getenv = func(name string) (string, bool) {
		if v, ok := extra[name]; ok {
			return v, true
		}
		return base(name)
	}
	return e
}

func (r *borgRepo) borgeWithEnv(t *testing.T, extra map[string]string, args ...string) (string, string, int) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := Run(r.borgeEnvWith(&stdout, &stderr, extra), args)
	return stdout.String(), stderr.String(), code
}

// TestCompressibleBufferMatchesBorg is the test that makes the compression rows mean
// something.
//
// Both tools compress data generated by the same xorshift word soup, so the ratios and
// times can be compared directly. If the two generators drifted apart the numbers would
// still look plausible and would silently be measuring different inputs - so the bytes are
// pinned against what borg's generator actually produced.
func TestCompressibleBufferMatchesBorg(t *testing.T) {
	b := &cpuBench{compressibl: map[int][]byte{}}
	got := b.compressibleBuffer(64)

	// Captured from borg's compressible_buffer(64) in benchmark_cmd.py.
	want := "object in\nof segment hash to index\ncontent archive directory key"
	if string(got) != want {
		t.Errorf("the word soup differs from borg's, so the compression rows are not comparable:\n"+
			"  borge: %q\n  borg:  %q", string(got), want)
	}
	if len(got) != 64 {
		t.Errorf("compressibleBuffer(64) returned %d bytes", len(got))
	}

	// It has to be deterministic across calls, or two runs of the benchmark would not be
	// comparable with each other either.
	if string(b.compressibleBuffer(64)) != want {
		t.Error("compressibleBuffer is not deterministic")
	}

	// And it has to actually compress. Random data would send every codec down its
	// incompressible fast path, which is the failure borg's comment warns about.
	big := (&cpuBench{compressibl: map[int][]byte{}}).compressibleBuffer(1 << 20)
	if distinct := countDistinctBytes(big); distinct > 40 {
		t.Errorf("the generated data uses %d distinct byte values; it is meant to be "+
			"text-like and compressible", distinct)
	}
}

func countDistinctBytes(b []byte) int {
	var seen [256]bool
	n := 0
	for _, c := range b {
		if !seen[c] {
			seen[c] = true
			n++
		}
	}
	return n
}

// benchRowRe matches a measurement row: spec, size, seconds, rate.
var benchRowRe = regexp.MustCompile(`^(\S.*?)\s{2,}(\S+ \S+|\d+k Items)\s+([\d.]+)s\s+([\d.]+) (MB/s|kItems/s)`)

// TestBenchmarkCPURunsEverySection.
func TestBenchmarkCPURunsEverySection(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")
	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CPU_TEST": "1"},
		"benchmark", "cpu")
	if code != ExitOK {
		t.Fatalf("benchmark cpu exited %d\n%s", code, stderr)
	}

	for _, section := range []string{"Chunkers", "Cryptographic hashes / MACs", "Encryption",
		"Compression", "msgpack"} {
		if !strings.Contains(stdout, section) {
			t.Errorf("no %q section:\n%s", section, stdout)
		}
	}

	// Every algorithm borge implements has to appear. A section header with no rows under
	// it would satisfy the check above.
	for _, spec := range []string{
		"fixed,1048576", "fastcdc,19,23,21,2", "buzhash64,19,23,21,4095,2", "buzhash,19,23,21,4095",
		"blake3", "hmac-sha256", "blake2b-256",
		"aes-256-ocb", "chacha20-poly1305",
		"lz4", "zstd,3", "zlib,6", "lzma,6",
	} {
		if !strings.Contains(stdout, spec) {
			t.Errorf("no row for %q:\n%s", spec, stdout)
		}
	}

	// And every row has to carry a real measurement. A row reporting zero bytes or an
	// unparseable rate is a row that measured nothing.
	rows := 0
	for _, line := range strings.Split(stdout, "\n") {
		m := benchRowRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		rows++
		if m[3] == "0.000" && m[4] == "0.0" {
			t.Errorf("row measured nothing: %q", line)
		}
	}
	if rows < 20 {
		t.Errorf("only %d measurement rows; expected one per algorithm and buffer size:\n%s",
			rows, stdout)
	}
}

// TestBenchmarkCPUSelectsSections: a flag narrows the run to that section alone.
func TestBenchmarkCPUSelectsSections(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")
	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CPU_TEST": "1"},
		"benchmark", "cpu", "--hashing")
	if code != ExitOK {
		t.Fatalf("benchmark cpu --hashing exited %d\n%s", code, stderr)
	}
	if !strings.Contains(stdout, "hmac-sha256") {
		t.Errorf("--hashing did not run the hashes:\n%s", stdout)
	}
	for _, other := range []string{"Chunkers", "Encryption", "Compression", "msgpack"} {
		if strings.Contains(stdout, other) {
			t.Errorf("--hashing also ran %q:\n%s", other, stdout)
		}
	}
}

// TestBenchmarkCPUJSON.
func TestBenchmarkCPUJSON(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")
	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CPU_TEST": "1"},
		"benchmark", "cpu", "--json")
	if code != ExitOK {
		t.Fatalf("benchmark cpu --json exited %d\n%s", code, stderr)
	}

	var doc map[string][]map[string]any
	if err := json.Unmarshal([]byte(stdout), &doc); err != nil {
		t.Fatalf("the output is not JSON: %v\n%s", err, stdout)
	}
	for _, section := range []string{"chunkers", "hashes", "encryption", "compression", "msgpack"} {
		rows, ok := doc[section]
		if !ok {
			t.Errorf("no %q section in the JSON", section)
			continue
		}
		if len(rows) == 0 {
			t.Errorf("the %q section has no rows", section)
		}
	}

	// The two fields borge adds beyond borg's are the ones a stage 9 comparison needs, so
	// they have to be present rather than optional.
	for _, row := range doc["chunkers"] {
		if _, ok := row["setup_per_call"]; !ok {
			t.Errorf("a chunker row has no setup_per_call: %v", row)
		}
	}
	for _, row := range doc["compression"] {
		ratio, ok := row["ratio"].(float64)
		if !ok {
			t.Errorf("a compression row has no ratio: %v", row)
			continue
		}
		if ratio <= 1 {
			t.Errorf("a compression row reports a ratio of %.2f; the generated data is "+
				"meant to compress: %v", ratio, row)
		}
	}
}

// TestBenchmarkCRUDMeasuresTheRealCommands.
//
// The point of crud is that it drives the ordinary commands, so the test checks the
// repository afterwards as well as the output: an archive left behind would mean a
// measurement ran against a repository that was not in the state the next row assumes.
func TestBenchmarkCRUDMeasuresTheRealCommands(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")
	data := t.TempDir()

	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CRUD_TEST": "1"},
		"benchmark", "crud", "-r", r.path, data)
	if code != ExitOK {
		t.Fatalf("benchmark crud exited %d\n%s", code, stderr)
	}

	// Four operations for each of the two test samples.
	for _, id := range []string{"C-Z-TEST", "R-Z-TEST", "U-Z-TEST", "D-Z-TEST",
		"C-R-TEST", "R-R-TEST", "U-R-TEST", "D-R-TEST"} {
		letter, sample := id[:1], id[2:]
		if !strings.Contains(stdout, letter+"-"+sample) {
			t.Errorf("no %s row:\n%s", id, stdout)
		}
	}

	// borg leaves no archives behind and neither may borge: the benchmark's own archives
	// would otherwise be counted by whatever ran next.
	if names := borgArchiveNames(t, r); len(names) != 0 {
		t.Errorf("the benchmark left %d archive(s) behind: %v", len(names), names)
	}
	// Nor may it leave its input data.
	if entries := dirEntryNames(t, data); len(entries) != 0 {
		t.Errorf("the benchmark left its input data behind: %v", entries)
	}
	// And the repository has to still be sound, since every row wrote and deleted in it.
	if out, err := r.runErr("check", "-r", r.path); err != nil {
		t.Fatalf("borg check fails after the benchmark: %v\n%s", err, out)
	}
}

// dirEntryNames lists what a directory holds, for the "cleaned up after itself" checks.
func dirEntryNames(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	return names
}

// TestBenchmarkCRUDMatchesBorgsRowShape.
//
// The timings cannot be compared - they are the measurement - but the row shape can, and
// it is what a script parsing either tool's output depends on.
func TestBenchmarkCRUDMatchesBorgsRowShape(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")

	shape := func(out string) []string {
		// Replace every number with "#", so what is left is the format.
		digits := regexp.MustCompile(`[\d.]+`)
		var rows []string
		for _, line := range strings.Split(out, "\n") {
			if line = strings.TrimSpace(line); line == "" {
				continue
			}
			rows = append(rows, digits.ReplaceAllString(line, "#"))
		}
		return rows
	}

	cmd := exec.Command(r.binary, "benchmark", "crud", "-r", r.path, t.TempDir())
	cmd.Env = append(r.env(), "_BORG_BENCHMARK_CRUD_TEST=1")
	borgOut, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("borg benchmark crud failed: %v\n%s", err, borgOut)
	}
	want := shape(string(borgOut))
	if len(want) != 8 {
		t.Fatalf("borg printed %d rows, not the expected 8; the comparison below assumes "+
			"its format:\n%s", len(want), borgOut)
	}

	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CRUD_TEST": "1"},
		"benchmark", "crud", "-r", r.path, t.TempDir())
	if code != ExitOK {
		t.Fatalf("borge benchmark crud exited %d\n%s", code, stderr)
	}
	got := shape(stdout)

	if len(got) != len(want) {
		t.Fatalf("borge printed %d rows, borg %d\nborge:\n%s\nborg:\n%s",
			len(got), len(want), stdout, borgOut)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("row %d differs in shape\n  borg:  %s\n  borge: %s", i, want[i], got[i])
		}
	}
}

// TestBenchmarkCRUDJSONLines.
func TestBenchmarkCRUDJSONLines(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")

	stdout, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CRUD_TEST": "1"},
		"benchmark", "crud", "-r", r.path, "--json-lines", t.TempDir())
	if code != ExitOK {
		t.Fatalf("benchmark crud --json-lines exited %d\n%s", code, stderr)
	}

	lines := nonEmptyLines(stdout)
	if len(lines) != 8 {
		t.Fatalf("expected 8 JSON records, got %d:\n%s", len(lines), stdout)
	}
	for _, line := range lines {
		var rec map[string]any
		if err := json.Unmarshal([]byte(line), &rec); err != nil {
			t.Fatalf("a record is not JSON: %v\n%s", err, line)
		}
		for _, field := range []string{"command", "id", "io", "sample", "sample_count",
			"sample_random", "sample_size", "time"} {
			if _, ok := rec[field]; !ok {
				t.Errorf("the record has no %q field: %s", field, line)
			}
		}
	}
}

// TestBenchmarkCRUDNeedsARepository: pointed at a directory that is not one, it says so
// rather than creating one.
func TestBenchmarkCRUDNeedsARepository(t *testing.T) {
	r := newBorgRepo(t, "aes256-ocb")
	notARepo := t.TempDir()

	_, stderr, code := r.borgeWithEnv(t, map[string]string{"_BORGE_BENCHMARK_CRUD_TEST": "1"},
		"benchmark", "crud", "-r", notARepo, t.TempDir())
	if code != ExitError {
		t.Errorf("benchmark crud on a non-repository exited %d, want ExitError (%d)", code, ExitError)
	}
	if !strings.Contains(stderr, "not a repository") {
		t.Errorf("the error does not say what is wrong: %q", stderr)
	}
}

// TestBenchmarkUsage.
func TestBenchmarkUsage(t *testing.T) {
	var out, errOut strings.Builder
	e := &Env{Stdout: &out, Stderr: &errOut, Getenv: func(string) (string, bool) { return "", false }}

	if code := Run(e, []string{"benchmark"}); code != ExitOK {
		t.Errorf("bare 'benchmark' exited %d, want ExitOK", code)
	}
	for _, name := range []string{"crud", "cpu"} {
		if !strings.Contains(out.String(), name) {
			t.Errorf("the benchmark usage does not list %q:\n%s", name, out.String())
		}
	}

	out.Reset()
	errOut.Reset()
	if code := Run(e, []string{"benchmark", "no-such-thing"}); code != ExitError {
		t.Errorf("an unknown benchmark command exited %d, want ExitError", code)
	}
}
